// Command generate emits the immutable PostgreSQL equivalent of NameKey.
// Hex-encoded UTF-8 sequences make the migration portable to SQL_ASCII without
// interpreting arbitrary Unicode characters as a set of bytes to trim.
package main

import (
	"bytes"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"os"
	"strings"
	"unicode"

	"golang.org/x/text/cases"
)

func main() {
	fold := cases.Fold()
	mapping := map[string]string{}
	var spaces []string
	for r := rune(1); r <= unicode.MaxRune; r++ {
		if r >= 0xd800 && r <= 0xdfff {
			continue
		}
		value := string(r)
		key := hex.EncodeToString([]byte(value))
		if unicode.IsSpace(r) {
			spaces = append(spaces, "'"+key+"'")
		}
		if folded := fold.String(value); folded != value {
			mapping[key] = hex.EncodeToString([]byte(folded))
		}
	}
	encoded, err := json.MarshalIndent(mapping, "", " ")
	if err != nil {
		panic(err)
	}
	sql := strings.ReplaceAll(function, "FOLD_MAPPING", string(encoded))
	sql = strings.ReplaceAll(sql, "SPACE_SEQUENCES", strings.Join(spaces, ","))
	sql = fmt.Sprintf("-- Code generated by go generate ./internal/vocabulary; DO NOT EDIT.\n-- Case folding: pinned golang.org/x/text/cases; whitespace: Go Unicode %s.\n", unicode.Version) + sql
	if existing, err := os.ReadFile("../database/migrations/058_vocabulary_name_key.up.sql"); err == nil {
		if bytes.Equal(existing, []byte(sql)) {
			return
		}
		panic("frozen vocabulary normalization changed: add a reviewed forward migration instead of rewriting 058")
	} else if !os.IsNotExist(err) {
		panic(err)
	}
	if err := os.WriteFile("../database/migrations/058_vocabulary_name_key.up.sql", []byte(sql), 0644); err != nil {
		panic(err)
	}
}

const function = `
-- Return UTF-8 bytes so equality has identical semantics in UTF8 and SQL_ASCII.
-- Validate and consume complete UTF-8 sequences; never trim a multibyte byte set.
CREATE FUNCTION vocabulary_name_key(value text) RETURNS bytea
LANGUAGE plpgsql IMMUTABLE STRICT PARALLEL SAFE AS $$
DECLARE
 fold_map CONSTANT jsonb := 'FOLD_MAPPING'::jsonb;
 spaces CONSTANT text[] := ARRAY[SPACE_SEQUENCES];
 source bytea := pg_catalog.textsend(value);
 result bytea := ''::bytea;
 pending_space bytea := ''::bytea;
 pos integer := 0;
 width integer;
 first_byte integer;
 second_byte integer;
 continuation integer;
 unit text;
 started boolean := false;
BEGIN
 WHILE pos < octet_length(source) LOOP
  first_byte := get_byte(source,pos);
  IF first_byte < 128 THEN width:=1;
  ELSIF first_byte BETWEEN 194 AND 223 THEN width:=2;
  ELSIF first_byte BETWEEN 224 AND 239 THEN width:=3;
  ELSIF first_byte BETWEEN 240 AND 244 THEN width:=4;
  ELSE RAISE EXCEPTION USING ERRCODE='23514', MESSAGE='vocabulary name must be valid UTF-8';
  END IF;
  IF pos+width > octet_length(source) THEN
   RAISE EXCEPTION USING ERRCODE='23514', MESSAGE='vocabulary name must be valid UTF-8';
  END IF;
  IF width>1 THEN
   FOR continuation IN 1..width-1 LOOP
    IF get_byte(source,pos+continuation) NOT BETWEEN 128 AND 191 THEN
     RAISE EXCEPTION USING ERRCODE='23514', MESSAGE='vocabulary name must be valid UTF-8';
    END IF;
   END LOOP;
   second_byte:=get_byte(source,pos+1);
   IF (first_byte=224 AND second_byte<160) OR (first_byte=237 AND second_byte>159)
    OR (first_byte=240 AND second_byte<144) OR (first_byte=244 AND second_byte>143) THEN
    RAISE EXCEPTION USING ERRCODE='23514', MESSAGE='vocabulary name must be valid UTF-8';
   END IF;
  END IF;
  unit:=encode(substring(source FROM pos+1 FOR width),'hex');
  IF unit=ANY(spaces) THEN
   IF started THEN pending_space:=pending_space || decode(unit,'hex'); END IF;
  ELSE
   result:=result || pending_space || decode(coalesce(fold_map->>unit,unit),'hex');
   pending_space:=''::bytea;
   started:=true;
  END IF;
  pos:=pos+width;
 END LOOP;
 RETURN result;
END $$;
`
